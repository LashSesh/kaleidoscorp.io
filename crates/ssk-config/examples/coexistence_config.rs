// Generates docs/examples/ingress-coexistence.yaml: the scenario of design 2.4, a
// Proxifier-like layer in front of a third-party tunnel application. Kaleidoscorp
// neither starts nor configures that application. Its Direct dial binds no
// interface or source address, so the operating system's route decides.
//
//   cargo run -p ssk-config --example coexistence_config > docs/examples/ingress-coexistence.yaml
//
// `tests/examples.rs` includes this file and fails when the checked-in example
// differs from `document()`, so the example cannot rot. The generator lints its own
// output before it prints.
use ssk_config::ingress::IngressHardening;
use ssk_config::routing::{RoutingAction, RoutingProfile, RoutingRule};
use ssk_config::{lint, AppConfig, ConfigFormat};

fn rule(
    id: &str,
    priority: u32,
    destination: Option<&str>,
    domain_suffix: Option<&str>,
    port: Option<u16>,
    action: RoutingAction,
) -> RoutingRule {
    RoutingRule {
        id: id.into(),
        priority,
        destination: destination.map(Into::into),
        domain_suffix: domain_suffix.map(Into::into),
        port,
        action,
        require_attestation: false,
    }
}

pub fn document() -> Result<String, Box<dyn std::error::Error>> {
    let mut config = AppConfig::default();
    config.routing.default_profile = "coexist".into();
    config.routing.profiles = vec![RoutingProfile {
        id: "coexist".into(),
        name: "Direct through the operating system route, proxy clients only".into(),
        rules: vec![
            rule(
                "deny-blocked-example",
                5,
                None,
                Some("blocked.example"),
                None,
                RoutingAction::Deny,
            ),
            rule(
                "echo-ipify",
                10,
                Some("api.ipify.org"),
                None,
                Some(443),
                RoutingAction::Direct,
            ),
            rule(
                "echo-ipify-dual",
                11,
                Some("api64.ipify.org"),
                None,
                Some(443),
                RoutingAction::Direct,
            ),
            rule(
                "echo-ipify-v6",
                12,
                Some("api6.ipify.org"),
                None,
                Some(443),
                RoutingAction::Direct,
            ),
            rule(
                "allow-rest-443",
                900,
                None,
                None,
                Some(443),
                RoutingAction::Direct,
            ),
            rule(
                "allow-rest-80",
                901,
                None,
                None,
                Some(80),
                RoutingAction::Direct,
            ),
        ],
    }];
    // The shipped default listener (127.0.0.1:10800), stated so the file does not
    // depend on a default staying put.
    config.ingress.enabled = true;
    config.ingress.hardening = IngressHardening::BestEffort;
    config.ingress.arm_on_start = false;
    config.validate()?;
    let body = serde_yaml::to_string(&config)?;

    let report = lint(&body, ConfigFormat::Yaml);
    if !report.ok || report.migrated_from.is_some() {
        return Err(format!("the example does not lint cleanly: {report:?}").into());
    }

    let header = "\
# Kaleidoscorp configuration, version 5: Direct through the operating system's route
# for proxy clients, beside a third-party tunnel application (design 2.4).
# Generated by `cargo run -p ssk-config --example coexistence_config`; a test fails
# when this file differs from that output, so regenerate it instead of editing it.
#
# Rules are matched by ascending priority and the first match wins; a flow that
# matches no rule is denied. The three `echo-ipify*` rules match by NAME: a client
# that resolves the name itself and sends an address does not match them and falls
# to `allow-rest-443`. The two `allow-rest-*` rules open every name on those ports
# for Direct; write narrower rules for less. An exact-IP `deny` rule would be added
# above them.
#
# `arm_on_start: false` keeps the proxy disarmed after a restart: arm it by hand once
# the tunnel application shows connected. `hardening: best_effort` is a visible
# operator choice; the default is `required`. `direct_address_families: ipv4_only`
# keeps Direct off IPv6, which a tunnel may not cover.
# This build validates the section and does not open a listener yet.
#
";
    Ok(format!("{header}{body}"))
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    print!("{}", document()?);
    Ok(())
}
