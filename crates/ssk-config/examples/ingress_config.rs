// Generates docs/examples/ingress.example.yaml: a complete, valid v5 configuration
// with the local proxy section enabled and every key of it at its default.
//
//   cargo run -p ssk-config --example ingress_config > docs/examples/ingress.example.yaml
//
// `tests/examples.rs` includes this file and fails when the checked-in example
// differs from `document()`, so the example cannot rot. The generator lints its own
// output (`ssk_config::lint`, the check `ssk config lint` runs) before it prints.
// The numbers in the header are read from the one table the validator reads.
use ssk_config::ingress::bounds;
use ssk_config::{lint, AppConfig, ConfigFormat};
use std::fmt::Write as _;

pub fn document() -> Result<String, Box<dyn std::error::Error>> {
    let mut config = AppConfig::default();
    config.ingress.enabled = true;
    config.validate()?;
    let body = serde_yaml::to_string(&config)?;

    let report = lint(&body, ConfigFormat::Yaml);
    if !report.ok || report.migrated_from.is_some() {
        return Err(format!("the example does not lint cleanly: {report:?}").into());
    }

    let mut header = String::from(
        "\
# Kaleidoscorp configuration, version 5, with the local proxy section enabled.
# Generated by `cargo run -p ssk-config --example ingress_config`; a test fails when
# this file differs from that output, so regenerate it instead of editing it.
#
# `routing` is the default: no rule, so every connection is denied. See
# ingress-coexistence.yaml for a complete scenario with rules.
# `ingress` shows every key at its default except `enabled`. `ingress: {}` is a valid,
# disabled section; a misspelled key anywhere in it is refused, not ignored.
# This build validates the section and does not open a listener yet.
#
# Numbers below `ingress`: key, default, accepted range.
",
    );
    for bound in bounds::ALL {
        writeln!(
            header,
            "#   {:<27} {:>9}  {}..={}",
            bound.key,
            bound.default,
            bound.range.start(),
            bound.range.end()
        )?;
    }
    writeln!(
        header,
        "# audit.segment_mib x audit.retain_segments may not exceed {} MiB. The ledger is\n\
         # kept by size only: there is no age limit and no key for one.\n#",
        bounds::MAX_LEDGER_MIB
    )?;
    Ok(header + &body)
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    print!("{}", document()?);
    Ok(())
}
